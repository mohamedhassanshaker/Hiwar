// Trims the vendored design-system bundle down to the components the console uses
// and writes them as an ES module that takes React from an import instead of a global.
//
// Seeds: Button, Tag, Badge, LogoModes and the icon components listed under "Icons"
// in the design system's readme, plus everything they reach through `__ds_scope.<Name>`.
// Run with `npm run ds:generate`; the output is committed and must stay byte-identical.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(root, "vendor", "tahseel-ds");
const outFile = join(root, "src", "ds", "generated", "ds-components.js");
const outTypes = join(root, "src", "ds", "generated", "ds-components.d.ts");

const NAMED_SEEDS = ["Button", "Tag", "Badge", "LogoModes"];

// `// <path>` + `try { (() => { <body> })(); } catch (e) { __ds_ns.__errors.push(...) }`
const BLOCK =
  /^try \{ \(\(\) => \{\n([\s\S]*?)\n\}\)\(\); \} catch \(e\) \{ __ds_ns\.__errors\.push\(\{ path: "([^"]+)", error: String\(\(e && e\.message\) \|\| e\) \}\); \}$/gm;

/** Reads a vendored file with normalised newlines, so a CRLF checkout generates the same module. */
function read(name) {
  return readFileSync(join(vendor, name), "utf8").split("\r\n").join("\n");
}

function iconSeeds(readme) {
  const row = readme.split("\n").find((line) => line.startsWith("| **Icons**"));
  if (!row) throw new Error("readme.md has no Icons row");
  return row.split("|")[3].split(",").map((name) => name.trim());
}

function parseBlocks(bundle) {
  const blocks = [];
  for (const match of bundle.matchAll(BLOCK)) {
    const [text, body, path] = match;
    const names = new Set();
    for (const assign of body.matchAll(/Object\.assign\(__ds_scope, \{([^}]*)\}\)/g)) {
      for (const pair of assign[1].split(",")) {
        const name = pair.split(":")[0].trim();
        if (name) names.add(name);
      }
    }
    for (const direct of body.matchAll(/^__ds_scope\.(\w+)\s*=/gm)) names.add(direct[1]);
    const deps = new Set();
    for (const use of body.matchAll(/__ds_scope\.(\w+)/g)) deps.add(use[1]);
    blocks.push({ path, names: [...names], deps: [...deps], text });
  }
  return blocks;
}

function closure(blocks, seeds) {
  const owner = new Map();
  blocks.forEach((block, index) => block.names.forEach((name) => owner.set(name, index)));
  const absent = seeds.filter((name) => !owner.has(name));
  if (absent.length) {
    console.warn(`generate-ds: not shipped by the design system, skipped: ${absent.join(", ")}`);
  }
  const kept = new Set();
  const queue = seeds.filter((name) => owner.has(name));
  while (queue.length) {
    const index = owner.get(queue.pop());
    if (kept.has(index)) continue;
    kept.add(index);
    for (const dep of blocks[index].deps) {
      if (owner.has(dep) && !kept.has(owner.get(dep))) queue.push(dep);
    }
  }
  return [...kept].sort((a, b) => a - b).map((index) => blocks[index]);
}

const seeds = [...NAMED_SEEDS, ...iconSeeds(read("readme.md"))];
const kept = closure(parseBlocks(read("_ds_bundle.js")), seeds);
const exported = kept
  .flatMap((block) => block.names)
  .filter((name) => !name.startsWith("__ds_default_"))
  .sort();

const header = `/* eslint-disable */
// GENERATED by scripts/generate-ds.mjs from vendor/tahseel-ds/_ds_bundle.js. Do not edit.
// ${kept.length} of the design system's components: the ones the console uses and their dependencies.
import React from "react";

const __ds_ns = {};
const __ds_scope = {};
const __ds_errors = [];
`;

const body = kept
  .map((block) => `\n// ${block.path}\n${block.text.replace("__ds_ns.__errors.push", "__ds_errors.push")}\n`)
  .join("");

const footer = `\n${exported.map((name) => `__ds_ns.${name} = __ds_scope.${name};`).join("\n")}

export const errors = __ds_errors;
export default __ds_ns;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, header + body + footer, "utf8");
writeFileSync(
  outTypes,
  `// GENERATED by scripts/generate-ds.mjs. Do not edit.
import type { ComponentType } from "react";

declare const components: Record<string, ComponentType<Record<string, unknown>> | undefined>;

export declare const errors: { path: string; error: string }[];
export default components;
`,
  "utf8",
);

console.log(`generate-ds: ${kept.length} components, ${exported.length} exported names`);
