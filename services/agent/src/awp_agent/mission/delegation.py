"""Registering a child mission, for delegation on the generic runtime (D08, D36).

Delegating to another configured agent is a child mission workflow, not a sub-agent:
Temporal needs agents and toolsets to exist at worker start, and a configured agent is
created at runtime. `delegate_to_agent` is the only delegation a mission is offered (D142).

The child is a real run. The platform gives it its own row, its own tokens and a grant
that is the parent run row intersected with the child agent's configuration, and refuses
it outright past the fan-out limits. All of that is decided there, in trusted code, from
the parent's run id — never from anything the model wrote (rule 4).
"""

from __future__ import annotations

from pydantic import BaseModel
from temporalio import activity

from awp_agent.clients import gateway_client, platform_mcp
from awp_agent.config import settings
from awp_agent.harness.types import SkillRef
from awp_agent.mission.deps import MissionDeps, model_tool_name
from awp_agent.mission.skills import granted_skills

START_TOOL = "run_start"


class ChildMissionWanted(BaseModel):
    """What the parent asks the platform to register."""

    parent_run_id: str
    #: Generated by the workflow with `workflow.uuid4()`, so it is the same on a replay.
    child_run_id: str
    agent_code: str
    #: The parent's plumbing credential. The platform checks it names the parent run.
    harness_token: str


class ChildMission(BaseModel):
    """The registered child's configuration, or why there is not one."""

    deps: MissionDeps | None = None
    #: What to tell the model. A refused delegation is a tool result, not a failed run.
    error: str = ""


@activity.defn(name="register_child_mission")
async def register_child_mission(wanted: ChildMissionWanted) -> ChildMission:
    """Ask the platform for the child's row, tokens and grant.

    Refused rather than raised, for the same reason the old path refused: an agent code
    the model invented is the model's mistake to recover from on its next turn, not a
    reason to take down the mission that asked. The fan-out limits answer the same way.
    """
    payload = await platform_mcp.call_tool(
        wanted.harness_token,
        START_TOOL,
        {
            "run_id": wanted.child_run_id,
            "parent_run_id": wanted.parent_run_id,
            "agent_code": wanted.agent_code,
            "context_type": "Console",
        },
    )
    if not isinstance(payload, dict):
        return ChildMission(error="the platform did not answer the delegation")
    if not payload.get("ok"):
        return ChildMission(error=str(payload.get("message") or "that agent is not available"))

    # Resolved here, in the activity: the child is a workflow, which may neither read the
    # environment nor the skill bundle (D119, D127). Without them the child had no platform
    # to call and no model to ask.
    skills = await granted_skills(
        [
            SkillRef.model_validate(skill)
            for skill in payload.get("skills", [])
            if isinstance(skill, dict)
        ],
        settings().skills_path,
    )
    return ChildMission(
        deps=MissionDeps(
            run_id=wanted.child_run_id,
            person_id=str(payload.get("person_id", "")),
            mcp_token=str(payload.get("mcp_token", "")),
            harness_token=str(payload.get("harness_token", "")),
            route=str(payload.get("route", "")),
            instructions=str(payload.get("instructions", "")),
            # Already narrowed to the parent's by the platform (D36). Copying the
            # parent's here instead would hand the child the reach that narrowing exists
            # to remove.
            granted_tools=[model_tool_name(str(name)) for name in payload.get("granted_tools", [])],
            tool_tiers={
                model_tool_name(str(tool.get("name", ""))): str(tool.get("tier", "T0"))
                for tool in payload.get("tools", [])
                if isinstance(tool, dict)
            },
            context_type="Console",
            skills=skills,
            mcp_url=settings().platform_mcp_url,
            gateway_url=gateway_client.openai_base_url(),
            sandbox_url=settings().sandbox_manager_url,
        )
    )
